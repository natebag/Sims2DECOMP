struct FamilyImpl {
    struct MemberVector {
        int* m_begin;
        int* m_end;
        int* m_capacity;
    };
    char pad[0x24];
    MemberVector m_members;

    void RemoveMember(int memberId);
};

void FamilyImpl::RemoveMember(int memberId) {
    int* begin = m_members.m_begin;
    int* end = m_members.m_end;
    if (begin == end) return;

    do {
        if (*begin == memberId) {
            int* src = begin + 1;
            if (src != end) {
                int* dst = begin;
                int n = end - src;
                while (n > 0) {
                    *dst++ = *src++;
                    n--;
                }
            }
            m_members.m_end = m_members.m_end - 1;
            return;
        }
        begin++;
    } while (begin != end);
}
